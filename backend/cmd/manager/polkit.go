package main

import (
	"encoding/json"
	"fmt"
	"io"
	"strings"

	"homelab-manager/backend/internal/domain"
)

// managerAccount is the system account the Manager runs as; the polkit
// rules grant their actions to it alone.
const managerAccount = "homelab-manager"

// polkitRuleFile is where the administrator installs the generated rule.
const polkitRuleFile = "/etc/polkit-1/rules.d/50-homelab-manager.rules"

// polkitRule renders the rule of SPEC_ADMINISTRATION.md § 2.1 for the allow
// list: manage-units for the Manager account only, on the listed units
// only, with the four verbs of § 5.2 only. An empty list grants nothing.
// The names are validated unit names, written as JSON strings.
func polkitRule(units domain.ManageableUnits) (string, error) {
	names, err := json.Marshal(units.Names())
	if err != nil {
		return "", fmt.Errorf("encode the unit names: %w", err)
	}
	verbs := make([]string, 0, len(domain.UnitVerbs))
	for _, verb := range domain.UnitVerbs {
		verbs = append(verbs, string(verb))
	}
	encodedVerbs, err := json.Marshal(verbs)
	if err != nil {
		return "", fmt.Errorf("encode the verbs: %w", err)
	}
	account, err := json.Marshal(managerAccount)
	if err != nil {
		return "", fmt.Errorf("encode the account: %w", err)
	}
	var rule strings.Builder
	fmt.Fprintf(&rule, `// Homelab Manager: lets the %s account start, stop, restart and
// reload the units of systemd_manageable_units, and nothing else
// (SPEC_ADMINISTRATION.md § 2.1 and § 5.2): no other unit or verb, no
// enable, mask nor daemon-reload.
//
// Generated by "homelab-manager polkit-rule" from the service
// configuration: generate it again after each change of the list.
// Install as root:root 0644 in %s.
polkit.addRule(function (action, subject) {
    var units = %s;
    var verbs = %s;
    if (action.id === "org.freedesktop.systemd1.manage-units" &&
        subject.user === %s &&
        units.indexOf(action.lookup("unit")) >= 0 &&
        verbs.indexOf(action.lookup("verb")) >= 0) {
        return polkit.Result.YES;
    }
});
`, managerAccount, polkitRuleFile, names, encodedVerbs, account)
	return rule.String(), nil
}

// runCommand runs a sub-command of the Manager binary and returns its exit
// status. The only one is polkit-rule.
func runCommand(args []string, stdout, stderr io.Writer, load func() (Config, error)) int {
	if len(args) != 1 || args[0] != "polkit-rule" {
		fmt.Fprintln(stderr, "usage: homelab-manager [polkit-rule]")
		fmt.Fprintln(stderr, "  polkit-rule  print the polkit rule of systemd_manageable_units for "+polkitRuleFile)
		return 2
	}
	config, err := load()
	if err != nil {
		fmt.Fprintf(stderr, "configuration error: %v\n", err)
		return 1
	}
	rule, err := polkitRule(config.ManageableUnits)
	if err != nil {
		fmt.Fprintf(stderr, "polkit rule: %v\n", err)
		return 1
	}
	if _, err := io.WriteString(stdout, rule); err != nil {
		fmt.Fprintf(stderr, "write the rule: %v\n", err)
		return 1
	}
	return 0
}
